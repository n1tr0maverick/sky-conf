// Language switching functionality
let currentLang = localStorage.getItem('skyLang') || 'en';

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('skyLang', lang);
    document.documentElement.lang = lang;
    
    // Update all translatable elements
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        const translation = translations[lang][key];
        
        if (translation) {
            // Check if translation contains HTML
            if (translation.includes('<')) {
                element.innerHTML = translation;
            } else {
                element.textContent = translation;
            }
        }
    });
    
    // Update language toggle buttons
    document.querySelectorAll('.lang-option').forEach(option => {
        option.classList.toggle('active', option.dataset.lang === lang);
    });
}

function initLanguageToggle() {
    const langToggle = document.getElementById('langToggle');
    if (!langToggle) return;
    
    // Set initial language
    setLanguage(currentLang);
    
    // Add click handlers
    langToggle.querySelectorAll('.lang-option').forEach(option => {
        option.addEventListener('click', (e) => {
            e.stopPropagation();
            const lang = option.dataset.lang;
            if (lang !== currentLang) {
                setLanguage(lang);
            }
        });
    });
    
    // Toggle on button click (cycles between languages)
    langToggle.addEventListener('click', () => {
        const newLang = currentLang === 'en' ? 'pl' : 'en';
        setLanguage(newLang);
    });
}

// Export for use in main script
window.initLanguageToggle = initLanguageToggle;
window.setLanguage = setLanguage;
